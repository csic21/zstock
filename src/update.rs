    #[test]
    fn pinned_signature_verifies_exact_payload_and_rejects_tampering() {
        // Published RFC 8032 verification key, never the production trust root.
        let key =
            decode_hex::<32>("d75a980182b10ab7d54bfed3c964073a0ee172f3daa62325af021a68f707511a")
                .unwrap();
        let bytes = include_bytes!("../tests/fixtures/update-signed-v1.json");
        let manifest = verify_manifest(bytes, &key).unwrap();
        assert_eq!(manifest.version, "99.0.0");
        assert!(evaluate_manifest(manifest).unwrap().is_some());
        let mut envelope: serde_json::Value = serde_json::from_slice(bytes).unwrap();
        envelope["payload"] = serde_json::Value::String(
            envelope["payload"]
                .as_str()
                .unwrap()
                .replace("99.0.0", "99.0.1"),
        );
        assert!(verify_manifest(&serde_json::to_vec(&envelope).unwrap(), &key).is_err());
        assert!(verify_manifest(bytes, &[0; 32]).is_err());
        assert!(verify_manifest(br#"{"version":"99.0.0","platforms":{}}"#, &key).is_err());
        assert!(decode_hex::<32>("").is_err());
    }

    #[test]
    fn package_hash_and_official_versioned_https_url_are_mandatory() {
        let hash = "a".repeat(64);
        let valid = format!(
            "https://github.com/csic21/zstock/releases/download/v99.0.0/zstock-{}.zip",
            platform_key()
        );
        assert!(validate_asset("99.0.0", &valid, &hash).is_ok());
        for url in [
            valid.replace("https://", "http://"),
            valid.replace("csic21", "attacker"),
            format!("{valid}?redirect=evil"),
            valid.replace("v99.0.0", "v98.0.0"),
        ] {
            assert!(validate_asset("99.0.0", &url, &hash).is_err());
        }
        for hash in ["", "abc", &"x".repeat(64)] {
            assert!(validate_asset("99.0.0", &valid, hash).is_err());
        }
        let value = r#"{"version":"99.0.0","platforms":{"linux-x64":{"url":"https://example.test/update.zip"}}}"#;
        assert!(serde_json::from_str::<UpdateManifest>(value).is_err());
    }

